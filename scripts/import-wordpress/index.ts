// Migrates content from the WordPress export into this repo.
//
//   npm run import            (reads the newest *.WordPress.*.xml in the repo root)
//   npm run import -- --no-media   (skip downloading media)
//   npm run import -- --only=insights   (only Podcasts, Webinars and Reports)
//   npm run import -- --only=pages      (only Pillars, Services, Team Members and open roles)
//
// The export holds personal data and is gitignored; it lives only on the
// machine that runs the import. Re-running overwrites the imported files, so
// once Content Editors start editing Blog Posts, don't re-run it over them.
//
// Later importers (Case Studies, Pages) add their step to `main` below.

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';
import { parseWxr, type Wxr } from './wxr.ts';
import { importBlogPosts, type ImportedBlogPost, type BlogPostImport } from './blog-posts.ts';
import { importCaseStudies } from './case-studies.ts';
import { importIndustries } from './industries.ts';
import { attachmentUrls, downloadMedia, notInRepo } from './media.ts';
import { importInsightItems } from './insights-step.ts';
import { withoutMigrated } from './pending.ts';
import { importServices } from './services.ts';
import { importTeamMembers, importCareers } from './people-and-roles.ts';
import { rm } from 'node:fs/promises';
import { pillarLabels } from '../../src/data/taxonomy.ts';
import type { InventoryEntry } from '../../tests/url-parity/parity.ts';

const ROOT = new URL('../../', import.meta.url);
const root = (path: string) => new URL(path, ROOT);

async function findExport(): Promise<string> {
  const files = (await readdir(ROOT)).filter((f) => /\.WordPress\..*\.xml$/.test(f)).sort();
  if (!files.length) throw new Error('No WordPress export (*.WordPress.*.xml) in the repo root.');
  return files.at(-1)!;
}

// YAML accepts JSON values, so JSON.stringify gives safe quoting for free.
function serialise(post: { data: object; body: string }): string {
  const lines = Object.entries(post.data).map(([key, value]) => `${key}: ${JSON.stringify(value)}`);
  return `---\n${lines.join('\n')}\n---\n\n${post.body}`;
}

async function write(path: string, contents: string) {
  await mkdir(dirname(root(path).pathname), { recursive: true });
  await writeFile(root(path), contents);
}

// Every migrated address that the live site served as a page leaves the
// pending list, which the URL parity check then guards.
async function shrinkPending(addresses: string[]) {
  const inventory: InventoryEntry[] = JSON.parse(await readFile(root('urls/inventory.json'), 'utf8'));
  const pages = new Set(inventory.filter((e) => e.expect === 'page').map((e) => e.path));
  const { json, removed } = withoutMigrated(
    await readFile(root('urls/pending.json'), 'utf8'),
    addresses.filter((a) => pages.has(a)),
  );
  await writeFile(root('urls/pending.json'), json);
  return removed;
}

function missingImagesReport(missing: BlogPostImport['missingImages']): string {
  const rows = missing.map((m) => `| ${m.address} | ${m.image} | ${m.alt.replace(/\|/g, '\\|') || '(no alt text)'} |`);
  return `# Blog Post images to replace

The live site no longer has these ${missing.length} images (it returns 404 for them), so they were left out of the migrated Blog Posts. Add a replacement to the post's body if it is still wanted.

Generated by \`npm run import\` from the WordPress export.

| Post | Missing image | Alt text |
| --- | --- | --- |
${rows.join('\n')}
`;
}

function withoutIndustryReport(posts: ImportedBlogPost[]): string {
  const missing = posts.filter((p) => p.data.industries.length === 0).sort((a, b) => a.address.localeCompare(b.address));
  const rows = missing.map((p) => `| ${p.data.title.replace(/\|/g, '\\|')} | ${p.data.pillars.map((s) => pillarLabels[s]).join(', ')} | ${p.address} |`);
  return `# Blog Posts without an Industry

These ${missing.length} of ${posts.length} Blog Posts have no Industry, so they appear in News only when no Industry filter is chosen. Add an \`industries\` value to each one's file in \`src/content/blog/\` to make it filterable.

Generated by \`npm run import\` from the WordPress export.

| Title | Pillar | Address |
| --- | --- | --- |
${rows.join('\n')}
`;
}

async function main() {
  const withMedia = !process.argv.includes('--no-media');
  const file = await findExport();
  console.log(`Reading ${file}`);
  // Parsed once; every importer reads the same parsed export.
  const wxr = parseWxr(await readFile(root(file), 'utf8'));

  if (process.argv.includes('--only=pages')) return importPages(wxr);

  // Podcasts, Webinars and Reports. `--only=insights` stops after this step,
  // leaving Blog Posts (which Content Editors may have edited) untouched.
  const insightAddresses = await importInsightItems(wxr, { withMedia, write });
  console.log(`Removed ${await shrinkPending(insightAddresses)} Podcast, Webinar and Report addresses from urls/pending.json`);
  if (process.argv.includes('--only=insights')) return;

  // Media first, so posts can leave out any image that couldn't be fetched.
  const media = [...importBlogPosts(wxr).media, ...importCaseStudies(wxr).media, ...importIndustries(wxr).media];
  if (withMedia) {
    const urls = [...attachmentUrls(wxr), ...media];
    console.log(`Downloading up to ${new Set(urls).size} media files (existing copies are skipped)`);
    const failures = await downloadMedia(urls);
    // Files the live site has already lost (404) are expected; anything else needs a re-run.
    const unexpected = failures.filter((f) => !f.endsWith('HTTP 404'));
    if (failures.length) console.log(`${failures.length - unexpected.length} media files are gone from the live site (404)`);
    if (unexpected.length) {
      console.error(`${unexpected.length} media files failed; re-run to retry:\n${unexpected.join('\n')}`);
      process.exitCode = 1;
    }
  }

  const blog = importBlogPosts(wxr, { missingMedia: await notInRepo(media) });
  for (const post of blog.posts) await write(post.file, serialise(post));
  console.log(`Wrote ${blog.posts.length} Blog Posts`);
  await write('docs/content-team/blog-posts-without-industry.md', withoutIndustryReport(blog.posts));
  await write('docs/content-team/blog-post-images-to-replace.md', missingImagesReport(blog.missingImages));
  console.log(`Left out ${blog.missingImages.length} images the live site no longer has`);
  console.log(`Removed ${await shrinkPending(blog.posts.map((p) => p.address))} addresses from urls/pending.json`);

  await importCaseStudiesAndIndustries(wxr);
  await importPages(wxr);
}

// The standard Pages migrated by hand (src/content/pages/, other than the
// open roles), with the Office list, leave the pending list here too.
const HAND_MIGRATED = [
  '/who-we-are/',
  '/who-we-are/our-team/',
  '/who-we-are/network/',
  '/what-we-do/',
  '/culture/',
  '/careers/',
  '/contact/',
  '/acceptable-use-policy/',
  '/modern-slavery-statement/',
  '/systango-partnership/',
];

async function importPages(wxr: Wxr) {
  const { pillars, services, unreadable } = importServices(wxr);
  for (const item of [...pillars, ...services]) await write(item.file, serialise(item));
  console.log(`Wrote ${pillars.length} Pillars and ${services.length} Services`);
  if (unreadable.length) {
    console.error(`Sections left out because their heading is unknown:\n${unreadable.map((u) => `${u.address}: ${u.reason}`).join('\n')}`);
    process.exitCode = 1;
  }

  const { members, withoutPhoto } = importTeamMembers(wxr);
  await rm(root('src/content/team/'), { recursive: true, force: true });
  for (const member of members) await write(member.file, serialise(member));
  console.log(`Wrote ${members.length} Team Members`);
  if (withoutPhoto.length) console.error(`Team Members left out for having no photo: ${withoutPhoto.join(', ')}`);

  const roles = importCareers(wxr);
  for (const role of roles) await write(role.file, serialise(role));
  console.log(`Wrote ${roles.length} open roles`);

  const addresses = [...pillars, ...services, ...roles].map((i) => i.address);
  console.log(`Removed ${await shrinkPending([...addresses, ...HAND_MIGRATED])} Pillar, Service and Page addresses from urls/pending.json`);
}

// The listing pages built for Case Studies and Industries, which leave the
// pending list along with the items.
const CASE_STUDY_LISTINGS = ['/insights/our-work/', '/industries/'];

async function importCaseStudiesAndIndustries(wxr: Wxr) {
  const { caseStudies, missingImages } = importCaseStudies(wxr, { missingMedia: await notInRepo(importCaseStudies(wxr).media) });
  for (const cs of caseStudies) await write(cs.file, serialise(cs));
  console.log(`Wrote ${caseStudies.length} Case Studies`);
  for (const m of missingImages) console.error(`Case Study image the live site no longer has: ${m.address} ${m.image}`);

  const { industries, unreadable } = importIndustries(wxr);
  for (const industry of industries) await write(industry.file, serialise(industry));
  console.log(`Wrote ${industries.length} Industries`);
  if (unreadable.length) {
    console.error(`Could not read these Industry pages; their layout changed:\n${unreadable.map((u) => `${u.address}: ${u.reason}`).join('\n')}`);
    process.exitCode = 1;
  }

  const addresses = [...caseStudies, ...industries].map((i) => i.address);
  console.log(`Removed ${await shrinkPending([...addresses, ...CASE_STUDY_LISTINGS])} Case Study and Industry addresses from urls/pending.json`);
}

await main();
