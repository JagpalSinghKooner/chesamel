// Migrates content from the WordPress export into this repo.
//
//   npm run import            (reads the newest *.WordPress.*.xml in the repo root)
//   npm run import -- --no-media   (skip downloading media)
//
// The export holds personal data and is gitignored; it lives only on the
// machine that runs the import. Re-running overwrites the imported files, so
// once Content Editors start editing Blog Posts, don't re-run it over them.
//
// Later importers (Case Studies, Pages) add their step to `main` below.

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';
import { parseWxr } from './wxr.ts';
import { importBlogPosts, type ImportedBlogPost, type BlogPostImport } from './blog-posts.ts';
import { attachmentUrls, downloadMedia, notInRepo } from './media.ts';
import { pillarLabels } from '../../src/data/taxonomy.ts';
import type { InventoryEntry } from '../../tests/url-parity/parity.ts';

const ROOT = new URL('../../', import.meta.url);
const root = (path: string) => new URL(path, ROOT);

async function findExport(): Promise<string> {
  const files = (await readdir(ROOT)).filter((f) => /\.WordPress\..*\.xml$/.test(f)).sort();
  if (!files.length) throw new Error('No WordPress export (*.WordPress.*.xml) in the repo root.');
  return files.at(-1)!;
}

// YAML accepts JSON values, so JSON.stringify gives safe quoting for free.
function serialise(post: ImportedBlogPost): string {
  const lines = Object.entries(post.data).map(([key, value]) => `${key}: ${JSON.stringify(value)}`);
  return `---\n${lines.join('\n')}\n---\n\n${post.body}`;
}

async function write(path: string, contents: string) {
  await mkdir(dirname(root(path).pathname), { recursive: true });
  await writeFile(root(path), contents);
}

// Every migrated address that the live site served as a page leaves the
// pending list, which the URL parity check then guards.
async function shrinkPending(addresses: string[]) {
  const inventory: InventoryEntry[] = JSON.parse(await readFile(root('urls/inventory.json'), 'utf8'));
  const pages = new Set(inventory.filter((e) => e.expect === 'page').map((e) => e.path));
  const migrated = new Set(addresses.filter((a) => pages.has(a)));
  const pending: string[] = JSON.parse(await readFile(root('urls/pending.json'), 'utf8'));
  const left = pending.filter((p) => !migrated.has(p));
  await writeFile(root('urls/pending.json'), JSON.stringify(left, null, 2) + '\n');
  return pending.length - left.length;
}

function missingImagesReport(missing: BlogPostImport['missingImages']): string {
  const rows = missing.map((m) => `| ${m.address} | ${m.image} | ${m.alt.replace(/\|/g, '\\|') || '(no alt text)'} |`);
  return `# Blog Post images to replace

The live site no longer has these ${missing.length} images (it returns 404 for them), so they were left out of the migrated Blog Posts. Add a replacement to the post's body if it is still wanted.

Generated by \`npm run import\` from the WordPress export.

| Post | Missing image | Alt text |
| --- | --- | --- |
${rows.join('\n')}
`;
}

function withoutIndustryReport(posts: ImportedBlogPost[]): string {
  const missing = posts.filter((p) => p.data.industries.length === 0).sort((a, b) => a.address.localeCompare(b.address));
  const rows = missing.map((p) => `| ${p.data.title.replace(/\|/g, '\\|')} | ${p.data.pillars.map((s) => pillarLabels[s]).join(', ')} | ${p.address} |`);
  return `# Blog Posts without an Industry

These ${missing.length} of ${posts.length} Blog Posts have no Industry, so they appear in News only when no Industry filter is chosen. Add an \`industries\` value to each one's file in \`src/content/blog/\` to make it filterable.

Generated by \`npm run import\` from the WordPress export.

| Title | Pillar | Address |
| --- | --- | --- |
${rows.join('\n')}
`;
}

async function main() {
  const withMedia = !process.argv.includes('--no-media');
  const file = await findExport();
  console.log(`Reading ${file}`);
  const xml = await readFile(root(file), 'utf8');

  // Media first, so posts can leave out any image that couldn't be fetched.
  const media = importBlogPosts(xml).media;
  if (withMedia) {
    const urls = [...attachmentUrls(parseWxr(xml)), ...media];
    console.log(`Downloading up to ${new Set(urls).size} media files (existing copies are skipped)`);
    const failures = await downloadMedia(urls);
    // Files the live site has already lost (404) are expected; anything else needs a re-run.
    const unexpected = failures.filter((f) => !f.endsWith('HTTP 404'));
    if (failures.length) console.log(`${failures.length - unexpected.length} media files are gone from the live site (404)`);
    if (unexpected.length) {
      console.error(`${unexpected.length} media files failed; re-run to retry:\n${unexpected.join('\n')}`);
      process.exitCode = 1;
    }
  }

  const blog = importBlogPosts(xml, { missingMedia: await notInRepo(media) });
  for (const post of blog.posts) await write(post.file, serialise(post));
  console.log(`Wrote ${blog.posts.length} Blog Posts`);
  await write('docs/content-team/blog-posts-without-industry.md', withoutIndustryReport(blog.posts));
  await write('docs/content-team/blog-post-images-to-replace.md', missingImagesReport(blog.missingImages));
  console.log(`Left out ${blog.missingImages.length} images the live site no longer has`);
  console.log(`Removed ${await shrinkPending(blog.posts.map((p) => p.address))} addresses from urls/pending.json`);
}

await main();
